def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_q(source, question, choices, answer, explain) -> str:
    c = ", ".join(f'"{esc(x)}"' for x in choices)
    return (
        f'    q("{esc(source)}",\n'
        f'      "{esc(question)}",\n'
        f"      [{c}],\n"
        f"      {answer}, \"{esc(explain)}\"),\n"
    )


def load_comcbt(exam_id: str, source: str, answers: list[int], only: list[int] | None = None) -> list[str]:
    data = json.loads(SCRAPED.read_text(encoding="utf-8"))[exam_id]
    lines = []
    for item in data:
        n = item["num"]
        if only is not None and n not in only:
            continue
        q = QUESTION_OVERRIDES.get((exam_id, n), item["q"])
        choices = CHOICE_OVERRIDES.get((exam_id, n), item["choices"])
        choices = [c for c in choices if c]
        if len(choices) != 4:
            raise ValueError(f"{source} Q{n}: need 4 choices, got {choices!r}")
        ans = MACHINE_2025_ANS[n] if exam_id == "16684" else answers[n - 1]
        explain = f"{source} {n}번 (comcbt)"
        lines.append(fmt_q(source, q, choices, ans, explain))
    return lines


