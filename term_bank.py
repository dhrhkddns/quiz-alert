def _build_questions() -> list[dict]:
    import random
    rng = random.Random(42)
    questions = []
    for term, subj, correct in TERM_DEFINITIONS:
        source = f"용어정의 {subj}"
        others = [d for t, s, d in TERM_DEFINITIONS if t != term and s == subj]
        if len(others) < 3:
            others += [d for t, s, d in TERM_DEFINITIONS if t != term and s != subj]
        rng.shuffle(others)
        wrong = others[:3]
        choices = [correct] + wrong
        rng.shuffle(choices)
        answer = choices.index(correct)
        question = f"「{term}」의 설명으로 옳은 것은?"
        explain = build_term_explain(term, correct, choices, answer)
        questions.append(q(source, question, choices, answer, explain))
    return questions


TERM_QUESTIONS = _build_questions()

