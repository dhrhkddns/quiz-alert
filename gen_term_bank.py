def build_term_questions() -> list[dict]:
    """용어 정의 4지선다 문제 생성."""
    from extra_bank import q

    rng = random.Random(42)
    by_subject: dict[str, list[tuple[str, str, str]]] = {}
    for term, subj, defn in TERMS:
        by_subject.setdefault(subj, []).append((term, subj, defn))

    questions = []
    for i, (term, subj, correct) in enumerate(TERMS):
        source = f"용어정의 {subj}"
        others = [d for t, s, d in TERMS if t != term and s == subj]
        if len(others) < 3:
            others += [d for t, s, d in TERMS if t != term and s != subj]
        rng.shuffle(others)
        wrong = others[:3]
        choices = [correct] + wrong
        rng.shuffle(choices)
        answer = choices.index(correct)
        question = f"「{term}」의 설명으로 옳은 것은?"
        explain = f"{term}: {correct}"
        questions.append(q(source, question, choices, answer, explain))
    return questions


