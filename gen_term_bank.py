seen_terms: set[str] = set()
unique: list[tuple[str, str, str]] = []
for term, subj, defn in TERMS:
    if term not in seen_terms:
        seen_terms.add(term)
        unique.append((term, subj, defn))
    if len(unique) >= 200:
        break

